"""Draft an ontology from a folder of CSV files (heuristic, no LLM needed).

The result is a *starting point*: keys, types and foreign-key relations are inferred from column
names and sample values. A person should review it and add descriptions, synonyms and metrics.
"""
import csv
import os
import re
from datetime import date
from pathlib import Path
from typing import Any

import yaml

from .schema import Ontology


def _singular(word: str) -> str:
    if word.endswith("ies") and len(word) > 3:
        return word[:-3] + "y"
    if word.endswith("s") and not word.endswith("ss") and len(word) > 3:
        return word[:-1]
    return word


def _pascal(stem: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[_\-\s]+", _singular(stem)) if part)


def _infer_type(values: list[str]) -> str:
    values = [v.strip() for v in values if v and v.strip()]
    if not values:
        return "string"

    def all_ok(fn) -> bool:
        try:
            for v in values:
                fn(v)
            return True
        except ValueError:
            return False

    if all(v.lower() in {"true", "false"} for v in values):
        return "boolean"
    if all_ok(int):
        return "integer"
    if all_ok(float):
        return "float"
    if all_ok(lambda v: date.fromisoformat(v[:10])) and all(len(v) >= 10 for v in values):
        return "date"
    return "string"


def suggest_ontology(csv_dir: "str | Path", name: str = "draft", relative_to: "str | Path | None" = None) -> dict[str, Any]:
    """``relative_to`` is the folder the ontology file will live in; source paths are written relative to it."""
    csv_dir = Path(csv_dir)
    rel_root = Path(relative_to) if relative_to else csv_dir
    files = sorted(csv_dir.glob("*.csv"))
    if not files:
        raise FileNotFoundError(f"No .csv files in {csv_dir}")

    tables: dict[str, dict[str, Any]] = {}
    for f in files:
        with open(f, newline="", encoding="utf-8-sig") as fh:
            reader = csv.DictReader(fh)
            headers = reader.fieldnames or []
            sample = [row for _, row in zip(range(200), reader)]
        stem = _singular(f.stem.lower())
        key = next((h for h in headers if h.lower() in ("id", f"{stem}_id")), None) or \
            next((h for h in headers if h.lower().endswith("_id")), headers[0] if headers else None)
        tables[f.stem] = {"file": Path(os.path.relpath(f, rel_root)).as_posix(), "concept": _pascal(f.stem), "stem": stem, "headers": headers,
                          "sample": sample, "key": key}

    by_stem = {t["stem"]: t for t in tables.values()}
    concepts, relations = [], []
    for t in tables.values():
        fk_cols = {}
        for h in t["headers"]:
            if h != t["key"] and h.lower().endswith("_id"):
                target = by_stem.get(_singular(h.lower()[:-3]))
                if target is not None and target is not t:
                    fk_cols[h] = target
        props = [
            {"name": h, "type": _infer_type([r.get(h, "") for r in t["sample"]]), "description": "TODO"}
            for h in t["headers"] if h != t["key"] and h not in fk_cols
        ]
        concepts.append({"name": t["concept"], "description": "TODO",
                         "source": {"adapter": "csv", "path": t["file"], "key": t["key"]}, "properties": props})
        for col, target in fk_cols.items():
            base = col[:-3]
            relations.append({"name": f"belongs_to_{base}", "from": t["concept"], "to": target["concept"],
                              "inverse": f"has_{t['stem']}s", "cardinality": "many_to_one",
                              "foreign_key": col, "description": "TODO"})
    draft = {"name": name, "version": "0.1", "description": "Draft generated by `ontolayer suggest`. Review before use.",
             "concepts": concepts, "relations": relations}
    Ontology.model_validate(draft)  # fail loudly if the draft is not valid
    return draft


def suggest_yaml(csv_dir: "str | Path", name: str = "draft", relative_to: "str | Path | None" = None) -> str:
    return yaml.safe_dump(suggest_ontology(csv_dir, name, relative_to), sort_keys=False, allow_unicode=True)
